"""Write the README results tables from eval/results/*.json. No number is typed by hand.

Replaces everything between <!-- results:start --> and <!-- results:end --> in README.md.
Planned rows that have no result file yet are shown with "–".

  python -m eval.make_table          # update README.md
  python -m eval.make_table --check  # exit 1 if README.md is out of date (for CI / pre-commit)
"""
from __future__ import annotations

import argparse
import json
import sys

from labeling.splits import ROOT
from labeling.validate import FIELDS

RESULTS = ROOT / "eval" / "results"
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"

# display order; rows not listed here are appended after them
PLANNED = [
    "Teacher (API)",
    "Small model, prompted",
    "Small model, fine-tuned (run 1)",
    "Small model, fine-tuned (run 2)",
    "DistilBERT (categorical fields)",
    "Majority class (reference)",
]


def p(x, digits=1):
    return "–" if x is None else f"{100 * x:.{digits}f}%"


def with_ci(r, key):
    lo, hi = r["ci95"][key]
    return f"{p(r[key])} <sub>({100 * lo:.0f}–{100 * hi:.0f})</sub>"


def render(results: dict[str, dict]) -> str:
    names = PLANNED + sorted(n for n in results if n not in PLANNED)
    L = [START, "",
         "Test set: 200 reviewed messages ([`data/final/test.jsonl`](data/final/test.jsonl)). "
         "Numbers in brackets are 95% bootstrap confidence intervals. Generated by "
         "[`eval/make_table.py`](eval/make_table.py) from [`eval/results/`](eval/results/); "
         "metric definitions in [`eval/eval.py`](eval/eval.py).", "",
         "| Model | Exact match | Field acc | Schema-valid | Valid JSON (strict) | Urgency: medium | p95 latency | Cost / 1K req |",
         "|---|---|---|---|---|---|---|---|"]
    notes = []
    for n in names:
        r = results.get(n)
        if r is None:
            L.append(f"| {n} | – | – | – | – | – | – | – |")
            continue
        lat = r.get("latency_s")
        lat_s = "–" if not lat or n.startswith("Majority") else f"{lat['p95']:.2f} s"
        cost = r.get("cost_per_1k_requests")
        cost_s = f"${cost['usd']:.3f}" if cost else "–"
        med = r["urgency_by_class"].get("medium", {}).get("acc")
        mark = f" [{len(notes) + 1}]" if (r.get("hardware") or r.get("notes")) else ""
        L.append(f"| {n}{mark} | {with_ci(r, 'exact_match')} | {with_ci(r, 'field_acc_mean')} | {p(r['schema_valid'])} | "
                 f"{p(r['valid_json_strict'])} | {p(med)} | {lat_s} | {cost_s} |")
        if mark:
            notes.append(" — ".join(x for x in (r.get("notes"), r.get("hardware")) if x and x != "none"))
    if notes:
        L.append("")
        L += [f"<sub>[{i}] {t}</sub><br>" for i, t in enumerate(notes, 1)]

    L += ["", "**Per-field accuracy**", "",
          "| Model | " + " | ".join(FIELDS) + " | intent macro-F1 | order_id false alarms | product false alarms |",
          "|---|" + "---|" * (len(FIELDS) + 3)]
    for n in names:
        r = results.get(n)
        if r is None:
            continue
        L.append(f"| {n} | " + " | ".join(p(r[f'acc_{f}']) for f in FIELDS)
                 + f" | {r['intent_macro_f1']:.3f} | {p(r['order_id']['false_alarm_rate'])} | {p(r['product']['false_alarm_rate'])} |")
    L += ["", END]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    results = {}
    for f in sorted(RESULTS.glob("*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        if r["name"] in results:
            raise SystemExit(f"duplicate result name {r['name']!r} ({f.name})")
        results[r["name"]] = r
    block = render(results)

    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md is missing the {START} / {END} markers")
    new = text[: text.index(START)] + block + text[text.index(END) + len(END):]
    if args.check:
        ok = new == text
        print("README results are up to date" if ok else "README results are OUT OF DATE: run python -m eval.make_table")
        sys.exit(0 if ok else 1)
    README.write_text(new, encoding="utf-8", newline="\n")
    print(f"updated {README.name}: {len(results)} result files -> rows: {', '.join(results)}")


if __name__ == "__main__":
    main()
