"""Compare teacher labels against the reference signals we already have, write a markdown report.

Reference signals (none of them is the final gold standard; the hand-checked test set is):
  - bitext_intent / bitext_category : Bitext's own labels
  - gt_order_id                     : order number we injected in prepare_data.py
  - hint_product                    : account tier we injected (e.g. "gold account")
urgency / sentiment have no reference -> we report distributions and list samples to eyeball.

  python -m labeling.pilot_report --labels data/labeled/pilot.jsonl --out labeling/pilot_report.md
"""
from __future__ import annotations

import argparse
import statistics
from collections import Counter
from pathlib import Path

from labeling.splits import PREPARED, load_jsonl


def norm_prod(p):
    return None if p is None else " ".join(p.lower().replace("-", " ").split())


def pct(a, b):
    return f"{a}/{b} ({100 * a / b:.1f}%)" if b else "n/a (0 rows)"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    ref = {r["id"]: r for s in ("train", "val", "test") for r in load_jsonl(PREPARED / f"{s}.jsonl")}
    labs = load_jsonl(args.labels)
    rej_path = args.labels.with_suffix(".rejects.jsonl")
    rejects = load_jsonl(rej_path) if rej_path.exists() else []
    rows = [(ref[l["id"]], l["label"], l) for l in labs]
    n = len(rows)

    intent_ok = sum(r["bitext_intent"] == y["intent"] for r, y, _ in rows)
    cat_ok = sum(r["bitext_category"] == y["category"] for r, y, _ in rows)
    with_oid = [(r, y) for r, y, _ in rows if r["gt_order_id"]]
    no_oid = [(r, y) for r, y, _ in rows if not r["gt_order_id"]]
    oid_ok = sum(y["order_id"] == r["gt_order_id"] for r, y in with_oid)
    oid_fp = sum(y["order_id"] is not None for r, y in no_oid)
    with_prod = [(r, y) for r, y, _ in rows if r["hint_product"]]
    prod_ok = sum(norm_prod(y["product"]) == norm_prod(r["hint_product"]) for r, y in with_prod)
    prod_nonnull_elsewhere = sum(y["product"] is not None for r, y, _ in rows if not r["hint_product"])

    L = [f"# Teacher pilot report: `{args.labels.as_posix()}`", ""]
    L += [f"Generated by `labeling/pilot_report.py`. Teacher: `{labs[0]['teacher'] if labs else '?'}`, "
          f"prompt `{labs[0].get('prompt_version', '?') if labs else '?'}`.", ""]
    L += ["## Validity", "",
          f"- valid labels: {pct(n, n + len(rejects))}; rejected after retries: {len(rejects)}",
          f"- needed >1 attempt: {sum(l['attempts'] > 1 for _, _, l in rows)}", ""]
    L += ["## Agreement with reference signals", "", "| Field | Agreement | Reference |", "|---|---|---|",
          f"| intent | {pct(intent_ok, n)} | Bitext label |",
          f"| category | {pct(cat_ok, n)} | Bitext label |",
          f"| order_id (rows with an id) | {pct(oid_ok, len(with_oid))} | injected id |",
          f"| order_id false positives (rows without) | {pct(oid_fp, len(no_oid))} | should be 0 |",
          f"| product (rows with a tier) | {pct(prod_ok, len(with_prod))} | injected tier |",
          f"| product non-null on other rows | {pct(prod_nonnull_elsewhere, n - len(with_prod))} | inspect below |", ""]

    L += ["## Distributions (no reference: eyeball)", ""]
    for fld in ("urgency", "sentiment"):
        c = Counter(y[fld] for _, y, _ in rows)
        L.append(f"- {fld}: " + ", ".join(f"{k} {v}" for k, v in c.most_common()))
    lat = [l["latency_s"] for _, _, l in rows]
    pt = [l["usage"]["prompt_tokens"] or 0 for _, _, l in rows]
    ot = [(l["usage"]["output_tokens"] or 0) + (l["usage"]["thoughts_tokens"] or 0) for _, _, l in rows]
    if rows:
        L += [f"- latency s: mean {statistics.mean(lat):.2f}, max {max(lat):.2f}",
              f"- tokens/request: prompt {statistics.mean(pt):.0f}, output incl. thinking {statistics.mean(ot):.0f}", ""]

    def table(title, items):
        L.extend([f"## {title} ({len(items)})", ""])
        if not items:
            L.extend(["_none_", ""]); return
        L.extend(["| id | text | expected | teacher |", "|---|---|---|---|"])
        for i, t, e, g in items:
            L.append(f"| {i} | {t.replace('|', '/')} | {e} | {g} |")
        L.append("")

    table("Intent disagreements", [(r["id"], r["text"], r["bitext_intent"], y["intent"])
                                   for r, y, _ in rows if r["bitext_intent"] != y["intent"]])
    table("order_id errors", [(r["id"], r["text"], r["gt_order_id"], y["order_id"])
                              for r, y, _ in rows if (r["gt_order_id"] or None) != y["order_id"]])
    table("product mismatches / extra products", [(r["id"], r["text"], r["hint_product"], y["product"])
                                                  for r, y, _ in rows
                                                  if norm_prod(r["hint_product"]) != norm_prod(y["product"])])
    L += ["## All labels (urgency / sentiment spot-check)", "", "| text | intent | urgency | sentiment |", "|---|---|---|---|"]
    for r, y, _ in rows:
        L.append(f"| {r['text'].replace('|', '/')} | {y['intent']} | {y['urgency']} | {y['sentiment']} |")

    args.out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L[:22]))
    print(f"\n-> wrote {args.out}")


if __name__ == "__main__":
    main()
